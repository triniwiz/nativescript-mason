import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const workspaceRoot = fileURLToPath(new URL('../../../', import.meta.url));

const target = 'wasm32-unknown-unknown';
const toolchain = '1.99.1';
const binaryen = 'binaryen@132.0.0';
const destination = resolve(workspaceRoot, 'packages/nativescript-masonkit/portable-css-evaluator.ts');
const work = mkdtempSync(resolve(tmpdir(), 'mason-portable-css-'));

function run(command, args, env = process.env) {
  const result = spawnSync(command, args, { cwd: workspaceRoot, env, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} exited with status ${result.status}`);
}

try {
  const rustc = spawnSync('rustup', ['which', '--toolchain', toolchain, 'rustc'], { encoding: 'utf8' });
  if (rustc.error) throw rustc.error;
  if (rustc.status !== 0) throw new Error(rustc.stderr.trim());
  run('mbx', ['build', '-p', 'mason-portable-css', '--target', target, '--release', '--locked'], {
    ...process.env,
    RUSTC: rustc.stdout.trim(),
    MBX_TARGET_VIEWS: '0',
    MBX_INCREMENTAL: '0',
    MBX_EAGER_INCREMENTAL: '0',
    MBX_LEARNED_INCREMENTAL: '0',
    CARGO_INCREMENTAL: '0',
    CARGO_PROFILE_RELEASE_OPT_LEVEL: 'z',
    CARGO_TARGET_DIR: resolve(work, 'target'),
    CARGO_ENCODED_RUSTFLAGS: [
      `--remap-path-prefix=${resolve(workspaceRoot)}=/mason`,
      `--remap-path-prefix=${process.env.CARGO_HOME || resolve(homedir(), '.cargo')}=/cargo`,
    ].join('\x1f'),
  });

  const output = resolve(work, 'evaluator.js');
  run('npm', ['exec', '--yes', `--package=${binaryen}`, '--', 'wasm2js',
    '--emscripten', '--all-features', '--disable-tail-call', '-Oz',
    resolve(work, 'target', target, 'release/mason_portable_css.wasm'), '-o', output]);
  const compiled = readFileSync(output, 'utf8');
  if (!compiled.startsWith('function instantiate(info) {')) throw new Error('Unexpected wasm2js factory');
  const source = [
    '// @ts-nocheck',
    '// Generated by tools/scripts/portable-css/generate.mjs from the Rust CSS parser.',
    'export ' + compiled.replace(/[ \t]+$/gm, '').trimEnd(),
    '',
  ].join('\n');
  if (process.argv.includes('--check')) {
    if (readFileSync(destination, 'utf8') !== source) throw new Error('Portable CSS evaluator is out of date');
  } else {
    writeFileSync(destination, source);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
